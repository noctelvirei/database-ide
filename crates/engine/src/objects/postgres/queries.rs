//! PostgreSQL catalog SQL. All substitutions are escaped literals or validated numeric keys.

pub(super) const CATALOG: &str = r#"
SELECT 'relation:' || c.oid::text AS key, n.nspname::text AS schema, c.relname::text AS name,
    CASE c.relkind WHEN 'r' THEN 'table' WHEN 'p' THEN 'table'
        WHEN 'v' THEN 'view' WHEN 'm' THEN 'materialized_view'
        WHEN 'S' THEN 'sequence' WHEN 'i' THEN 'index' WHEN 'I' THEN 'index' END AS kind,
    NULL::text AS signature
FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE c.relkind IN ('r', 'p', 'v', 'm', 'S', 'i', 'I')
UNION ALL
SELECT 'routine:' || p.oid::text, n.nspname::text, p.proname::text,
    CASE p.prokind WHEN 'p' THEN 'procedure' ELSE 'function' END,
    pg_catalog.pg_get_function_identity_arguments(p.oid)
FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
WHERE p.prokind IN ('f', 'p', 'w')
UNION ALL
SELECT 'schema:' || n.oid::text, NULL::text, n.nspname::text, 'schema', NULL::text
FROM pg_catalog.pg_namespace n
"#;

pub(super) const OBJECT_JSON: &str = r#"pg_catalog.json_build_object(
    'id', pg_catalog.json_build_object('database', current_database(), 'key', key),
    'schema', schema, 'name', name, 'kind', kind, 'signature', signature,
    'system', COALESCE(schema, name) = 'information_schema'
        OR left(COALESCE(schema, name), 3) = 'pg_')"#;

pub(super) const COLUMNS: &str = r#"
SELECT pg_catalog.json_build_object(
    'object_key', 'relation:' || a.attrelid::text,
    'name', a.attname, 'type_name', pg_catalog.format_type(a.atttypid, a.atttypmod),
    'nullable', NOT (a.attnotnull OR t.typnotnull),
    'default', CASE WHEN a.attgenerated = '' AND a.attidentity = ''
        THEN pg_catalog.pg_get_expr(d.adbin, d.adrelid) END,
    'identity', CASE a.attidentity WHEN 'a' THEN 'always' WHEN 'd' THEN 'by_default' END,
    'generated', CASE WHEN a.attgenerated <> '' THEN pg_catalog.json_build_object(
        'expression', pg_catalog.pg_get_expr(d.adbin, d.adrelid),
        'stored', a.attgenerated = 's') END)::text
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
"#;

pub(super) const CONSTRAINTS: &str = r#"
SELECT pg_catalog.json_build_object('name', conname,
    'kind', CASE contype WHEN 'p' THEN 'primary_key' WHEN 'u' THEN 'unique'
        WHEN 'f' THEN 'foreign_key' WHEN 'c' THEN 'check' WHEN 'x' THEN 'exclusion' END,
    'definition', pg_catalog.pg_get_constraintdef(oid, false))::text
FROM pg_catalog.pg_constraint
"#;

pub(super) const INDEXES: &str = r#"
SELECT pg_catalog.json_build_object(
    'object', pg_catalog.json_build_object(
        'id', pg_catalog.json_build_object('database', current_database(), 'key', 'relation:' || c.oid::text),
        'schema', n.nspname, 'name', c.relname, 'kind', 'index', 'signature', NULL,
        'system', n.nspname = 'information_schema' OR left(n.nspname, 3) = 'pg_'),
    'columns', ARRAY(SELECT pg_catalog.pg_get_indexdef(i.indexrelid, s, false)
        FROM pg_catalog.generate_series(1, i.indnatts) s ORDER BY s),
    'unique', i.indisunique, 'method', am.amname,
    'definition', pg_catalog.pg_get_indexdef(i.indexrelid),
    'constraint_backed', EXISTS (SELECT 1 FROM pg_catalog.pg_constraint con
        WHERE con.conindid = i.indexrelid AND con.contype IN ('p', 'u', 'x')))::text
FROM pg_catalog.pg_index i
JOIN pg_catalog.pg_class c ON c.oid = i.indexrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
JOIN pg_catalog.pg_am am ON am.oid = c.relam
"#;

pub(super) const SEQUENCE_OPTIONS: &str = r#"
' AS ' || pg_catalog.format_type(s.seqtypid, NULL)
|| ' INCREMENT BY ' || s.seqincrement || ' MINVALUE ' || s.seqmin
|| ' MAXVALUE ' || s.seqmax || ' START WITH ' || s.seqstart || ' CACHE ' || s.seqcache
|| CASE WHEN s.seqcycle THEN ' CYCLE' ELSE ' NO CYCLE' END
"#;

pub(super) const TABLE_COLUMNS: &str = r#"
SELECT string_agg(
    pg_catalog.quote_ident(a.attname) || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
    || CASE WHEN a.attcollation <> t.typcollation THEN
        ' COLLATE ' || pg_catalog.quote_ident(cn.nspname) || '.' || pg_catalog.quote_ident(co.collname)
        ELSE '' END
    || CASE WHEN a.attidentity <> '' THEN
        CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS' ELSE ' GENERATED BY DEFAULT' END
        || ' AS IDENTITY (' || (
            SELECT 'SEQUENCE NAME ' || pg_catalog.quote_ident(sn.nspname) || '.'
                || pg_catalog.quote_ident(sc.relname)
                || ' START WITH ' || s.seqstart || ' INCREMENT BY ' || s.seqincrement
                || ' MINVALUE ' || s.seqmin || ' MAXVALUE ' || s.seqmax || ' CACHE ' || s.seqcache
                || CASE WHEN s.seqcycle THEN ' CYCLE' ELSE ' NO CYCLE' END
            FROM pg_catalog.pg_depend dep
            JOIN pg_catalog.pg_class sc ON sc.oid = dep.objid
            JOIN pg_catalog.pg_namespace sn ON sn.oid = sc.relnamespace
            JOIN pg_catalog.pg_sequence s ON s.seqrelid = sc.oid
            WHERE dep.refobjid = a.attrelid AND dep.refobjsubid = a.attnum
                AND dep.refclassid = 'pg_catalog.pg_class'::regclass
                AND dep.classid = 'pg_catalog.pg_class'::regclass AND dep.deptype = 'i'
        ) || ')'
    WHEN a.attgenerated <> '' THEN
        ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, d.adrelid) || ')'
        || CASE a.attgenerated WHEN 's' THEN ' STORED' ELSE ' VIRTUAL' END
    WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, d.adrelid)
    ELSE '' END
    || CASE WHEN a.attnotnull THEN COALESCE((
        SELECT ' CONSTRAINT ' || pg_catalog.quote_ident(con.conname)
        FROM pg_catalog.pg_constraint con WHERE con.conrelid = a.attrelid
            AND con.contype = 'n' AND con.conkey = ARRAY[a.attnum]
        ), '') || ' NOT NULL' ELSE '' END,
    E',\n    ' ORDER BY a.attnum)
FROM pg_catalog.pg_attribute a
JOIN pg_catalog.pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
LEFT JOIN pg_catalog.pg_collation co ON co.oid = a.attcollation
LEFT JOIN pg_catalog.pg_namespace cn ON cn.oid = co.collnamespace
WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
"#;

pub(super) const TABLE_CONSTRAINTS: &str = r#"
SELECT string_agg('CONSTRAINT ' || pg_catalog.quote_ident(conname) || ' '
    || pg_catalog.pg_get_constraintdef(oid, false), E',\n    ' ORDER BY conname)
FROM pg_catalog.pg_constraint WHERE conrelid = c.oid AND contype IN ('p', 'u', 'f', 'c', 'x')
"#;

pub(super) const TABLE_INDEXES: &str = r#"
SELECT string_agg(pg_catalog.pg_get_indexdef(i.indexrelid) || ';', E'\n' ORDER BY ci.relname)
FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class ci ON ci.oid = i.indexrelid
WHERE i.indrelid = c.oid AND NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint con WHERE con.conindid = i.indexrelid
        AND con.contype IN ('p', 'u', 'x'))
"#;

pub(super) const TABLE_POLICIES: &str = r#"
SELECT string_agg('CREATE POLICY ' || pg_catalog.quote_ident(p.polname) || ' ON ' || qualified
    || CASE WHEN p.polpermissive THEN ' AS PERMISSIVE' ELSE ' AS RESTRICTIVE' END
    || ' FOR ' || CASE p.polcmd WHEN '*' THEN 'ALL' WHEN 'r' THEN 'SELECT'
        WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' END
    || ' TO ' || (SELECT string_agg(CASE WHEN role_oid = 0 THEN 'PUBLIC'
        ELSE pg_catalog.quote_ident(pg_catalog.pg_get_userbyid(role_oid)) END, ', ' ORDER BY position)
        FROM unnest(p.polroles) WITH ORDINALITY roles(role_oid, position))
    || COALESCE(' USING (' || pg_catalog.pg_get_expr(p.polqual, p.polrelid) || ')', '')
    || COALESCE(' WITH CHECK (' || pg_catalog.pg_get_expr(p.polwithcheck, p.polrelid) || ')', '')
    || E';\n', '' ORDER BY p.polname)
FROM pg_catalog.pg_policy p WHERE p.polrelid = c.oid
"#;

pub(super) const TABLE_COMMENTS: &str = r#"
SELECT string_agg(statement, E'\n' ORDER BY ordering, name) FROM (
    SELECT 0 AS ordering, '' AS name,
        'COMMENT ON TABLE ' || qualified || ' IS '
        || pg_catalog.quote_literal(pg_catalog.obj_description(c.oid, 'pg_class')) || ';' AS statement
    UNION ALL
    SELECT 1, a.attname::text, 'COMMENT ON COLUMN ' || qualified || '.'
        || pg_catalog.quote_ident(a.attname) || ' IS '
        || pg_catalog.quote_literal(pg_catalog.col_description(c.oid, a.attnum)) || ';'
    FROM pg_catalog.pg_attribute a WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
    UNION ALL
    SELECT 2, con.conname::text, 'COMMENT ON CONSTRAINT ' || pg_catalog.quote_ident(con.conname)
        || ' ON ' || qualified || ' IS '
        || pg_catalog.quote_literal(pg_catalog.obj_description(con.oid, 'pg_constraint')) || ';'
    FROM pg_catalog.pg_constraint con WHERE con.conrelid = c.oid
    UNION ALL
    SELECT 3, ci.relname::text, 'COMMENT ON INDEX ' || pg_catalog.quote_ident(n.nspname) || '.'
        || pg_catalog.quote_ident(ci.relname) || ' IS '
        || pg_catalog.quote_literal(pg_catalog.obj_description(ci.oid, 'pg_class')) || ';'
    FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class ci ON ci.oid = i.indexrelid
    WHERE i.indrelid = c.oid
) comments
"#;
